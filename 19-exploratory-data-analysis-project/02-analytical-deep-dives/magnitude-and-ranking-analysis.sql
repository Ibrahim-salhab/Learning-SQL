-- Magnitude Analysis: Compares raw volume or dollar values to understand total scale.
-- Ranking Analysis: Normalizes raw magnitudes into relative competition positions across departments, categories, or regions.
-- Pareto Principle: Typically, 80% of total revenue is generated by ~20% of top-performing SKUs or high-tier customers.
