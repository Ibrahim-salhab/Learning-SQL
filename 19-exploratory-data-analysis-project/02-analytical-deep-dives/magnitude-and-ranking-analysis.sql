-- ------------------------------------------------------------
-- 1. Product Magnitude & Ranking Analysis
-- ------------------------------------------------------------

-- Identify the Top 5 revenue-generating products with ranking functions
WITH product_revenue AS (
    SELECT
        p.product_id,
        p.product_name,
        p.category_name,
        SUM(f.quantity_sold) AS total_units_sold,
        SUM(f.total_revenue) AS total_revenue_generated
    FROM gold.fact_sales AS f
    INNER JOIN gold.dim_products AS p
        ON f.product_key = p.product_key
    GROUP BY p.product_id, p.product_name, p.category_name
)
SELECT
    product_name,
    category_name,
    total_units_sold,
    total_revenue_generated,
    DENSE_RANK() OVER(ORDER BY total_revenue_generated DESC) AS overall_revenue_rank,
    DENSE_RANK() OVER(PARTITION BY category_name ORDER BY total_revenue_generated DESC) AS category_revenue_rank
FROM product_revenue
ORDER BY overall_revenue_rank;


-- ------------------------------------------------------------
-- 2. Pareto Analysis (The 80/20 Principle in Revenue)
-- ------------------------------------------------------------

-- Determine what percentage of cumulative revenue is driven by top products
WITH product_sales AS (
    SELECT
        p.product_name,
        SUM(f.total_revenue) AS product_revenue
    FROM gold.fact_sales AS f
    INNER JOIN gold.dim_products AS p
        ON f.product_key = p.product_key
    GROUP BY p.product_name
),
cumulative_pareto AS (
    SELECT
        product_name,
        product_revenue,
        SUM(product_revenue) OVER(
            ORDER BY product_revenue DESC
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS running_cumulative_revenue,
        SUM(product_revenue) OVER() AS grand_total_revenue
    FROM product_sales
)
SELECT
    product_name,
    product_revenue,
    running_cumulative_revenue,
    ROUND(running_cumulative_revenue * 100.0 / grand_total_revenue, 2) AS cumulative_revenue_share_pct
FROM cumulative_pareto
ORDER BY product_revenue DESC;


